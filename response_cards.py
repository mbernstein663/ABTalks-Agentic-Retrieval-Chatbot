"""Compact, transparent retrieval evidence UI for Streamlit."""

import json
from typing import Any

import streamlit as st


def render_response_extras(
    chunk_ids: list[str] | None = None,
    tool_result: dict[str, Any] | None = None,
    tool_calls: list[dict[str, Any]] | None = None,
):
    """Present each MCP call separately and preserve SQL/vector source IDs."""
    chunk_ids = list(chunk_ids or [])
    tool_calls = list(tool_calls or [])
    if not (chunk_ids or tool_calls or tool_result):
        return

    label_parts = ["Retrieval details"]
    if tool_calls:
        label_parts.append(f"{len(tool_calls)} MCP call{'s' if len(tool_calls) != 1 else ''}")
    if chunk_ids:
        label_parts.append(f"{len(chunk_ids)} policy source{'s' if len(chunk_ids) != 1 else ''}")

    with st.expander(" · ".join(label_parts), expanded=False):
        st.caption("Evidence returned by the retrieval pipeline, not generated by the assistant.")
        for index, call in enumerate(tool_calls, start=1):
            name = str(call.get("name") or "Unknown tool")
            success = call.get("status") == "success"
            with st.container(border=True):
                st.markdown(f"**{index}. {name}**")
                st.caption("Successful retrieval" if success else "Tool reported an error")
                st.caption("Tool arguments")
                st.code(json.dumps(call.get("input"), indent=2, ensure_ascii=False, default=str), language="json")
                st.caption("Tool result")
                st.code(json.dumps(call.get("result"), indent=2, ensure_ascii=False, default=str), language="json")

        # SQL fallback and some MCP routes return a standalone structured object.
        if tool_result and not tool_calls:
            st.markdown("**Structured result**")
            st.code(json.dumps(tool_result, indent=2, ensure_ascii=False, default=str), language="json")

        if chunk_ids:
            st.markdown("**Policy sources**")
            st.caption("Retrieved document identifiers")
            for chunk_id in chunk_ids:
                st.code(str(chunk_id), language=None)
